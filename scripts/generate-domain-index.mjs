// Generates the "## Domains" section of docs/AUTHORING-PARTS.md from the domain
// registry (src/framework/domains/registry.js) and writes it in place. The output is
// COMMITTED; test/domain-index.test.js fails when the committed block drifts from the
// registry. Run it after adding or editing a domain manifest:
//
//   npm run docs:domains
//
// The section is the index an agent that has never heard of a domain reads: one line
// per domain — its title, the request class it serves (the manifest's `when`), the
// import line and the guide — placed right after Quickstart, before any geometry.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DOMAINS } from "../src/framework/domains/registry.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const GUIDE = resolve(ROOT, "docs/AUTHORING-PARTS.md");

export const GENERATED_START = "<!-- generated by scripts/generate-domain-index.mjs from src/framework/domains/registry.js; do not edit by hand -->";
export const GENERATED_END = "<!-- end generated -->";
const HEADING = "## Domains";

// The guide column links the file relative to docs/, where this guide lives.
const guideLink = (guide) => `[\`${guide}\`](${posix.relative("docs", guide)})`;
const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

export function renderDomainIndex(domains) {
  const rows = domains.map((d) =>
    `| ${cell(d.title)} | ${cell(d.when)} | \`import { … } from "${d.subpath}"\` | ${guideLink(d.guide)} |`);
  return [
    HEADING,
    "",
    "partforge's core is the kernel, the part contract and the panel. Everything past that is",
    "a **domain**: a separate guide you read only when a request calls for it. Each line",
    "names the request class, the import, and the guide. When a part matches a domain's",
    "description, read that guide first.",
    "",
    GENERATED_START,
    "| Domain | Use it for | Import | Guide |",
    "|---|---|---|---|",
    ...rows,
    GENERATED_END,
    "",
    "---",
    "",
    "",
  ].join("\n");
}

// Replaces the generated block in place, or inserts the whole section right after
// Quickstart (before "## Before geometry") when the guide has none yet.
export function applyDomainIndex(guide, domains) {
  const section = renderDomainIndex(domains);
  const start = guide.indexOf(GENERATED_START);
  if (start !== -1) {
    const end = guide.indexOf(GENERATED_END, start);
    if (end === -1) throw new Error("generate-domain-index: the guide has a start marker but no end marker");
    const blockStart = section.indexOf(GENERATED_START);
    const blockEnd = section.indexOf(GENERATED_END) + GENERATED_END.length;
    return guide.slice(0, start) + section.slice(blockStart, blockEnd) + guide.slice(end + GENERATED_END.length);
  }
  const anchor = "\n## Before geometry: state the engineering intent\n";
  const at = guide.indexOf(anchor);
  if (at === -1) throw new Error("generate-domain-index: cannot find the section after Quickstart to insert before");
  return guide.slice(0, at + 1) + section + guide.slice(at + 1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const before = readFileSync(GUIDE, "utf8");
  const after = applyDomainIndex(before, DOMAINS);
  if (after !== before) writeFileSync(GUIDE, after);
  console.log(`${after === before ? "unchanged" : "updated"}: docs/AUTHORING-PARTS.md (${DOMAINS.length} domain${DOMAINS.length === 1 ? "" : "s"})`);
}
