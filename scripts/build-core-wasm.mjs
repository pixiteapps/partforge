// Builds the native core (native/*.cpp) into ONE WebAssembly module and writes
// it as src/framework/core/core-wasm.js — the bytes base64-encoded inside a plain
// ES module, stamped with a hash of the sources and flags that produced them.
//
//   node scripts/build-core-wasm.mjs            # needs Emscripten's em++ on PATH
//   node scripts/build-core-wasm.mjs --check    # no compiler: exit 1 if stale
//
// Why a JS module and not a .wasm file: partforge ships as source and runs in a
// browser worker, Node (CLI, tests, a host's server), and hosts that load it from
// a blob: URL. A sibling .wasm would need a loader per environment (fetch vs fs,
// asset URLs a bundler must rewrite); an import works the same everywhere, and the
// module instantiates synchronously from the bytes.
//
// The generated file is committed. test/core-wasm.test.js recomputes the source
// hash (no compiler needed) so a C++ edit without a rebuild fails CI.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const NATIVE = join(ROOT, "native");
const OUT = join(ROOT, "src", "framework", "core", "core-wasm.js");

export const EXPORTS = [
  "malloc", "free",
  "cn_create", "cn_finish", "cn_positions", "cn_normals", "cn_edges", "cn_edge_floats",
  "cn_feature_ids", "cn_feature_count", "cn_feature_labels", "cn_destroy",
  "bvh_build", "bvh_triangle_count", "bvh_root_bounds", "bvh_raycast", "bvh_closest_point",
  "bvh_distance_to", "bvh_min_wall", "bvh_fingerprint", "bvh_destroy",
  "ip_math_probe",
  "ip_session_create", "ip_session_destroy", "ip_tex_add", "ip_prog_add", "ip_eval",
  "ip_sample", "ip_leaf_vals", "ip_clipped",
  "ip_mesh", "ip_vertex_count", "ip_positions", "ip_index_count", "ip_indices", "ip_vert_leaf",
  "ip_mesh_load", "ip_project", "ip_cleanup", "ip_normals", "ip_detail",
];
// -ffp-contract=off: the core must round every operation exactly as the JS does
// (see native/js_math.h). WebAssembly has no FMA to fuse into, but say so anyway.
// -msimd128 lets the compiler run independent lanes two at a time (the implicit
// interpreter's lane loops): f64x2 add/sub/mul/div/sqrt round each lane exactly as
// the scalar ops do, and without -ffast-math nothing is reassociated, so the bits
// are unchanged (test/core-parity.test.js, test/implicit-native-*.test.js). Not
// -mrelaxed-simd, whose madd is a fused multiply-add. Every engine partforge
// targets has had SIMD since 2023 (Safari 16.4); one without it fails to compile
// the module, which is the core's ordinary `boot_failed` fallback to the JS.
export const FLAGS = [
  "-O3", "-std=c++17", "-fno-exceptions", "-fno-rtti", "-ffp-contract=off", "-msimd128",
  "--no-entry", "-sSTANDALONE_WASM", "-sALLOW_MEMORY_GROWTH=1", "-sINITIAL_MEMORY=16MB",
  `-sEXPORTED_FUNCTIONS=${EXPORTS.map((e) => `_${e}`).join(",")}`,
];

// The hash covers every source file's bytes (sorted by name) and the flags.
export function sourceHash() {
  const h = createHash("sha256");
  for (const f of readdirSync(NATIVE).filter((n) => /\.(h|cpp)$/.test(n)).sort()) {
    h.update(f).update("\0").update(readFileSync(join(NATIVE, f))).update("\0");
  }
  h.update(FLAGS.join(" "));
  return h.digest("hex");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const hash = sourceHash();
  if (process.argv.includes("--check")) {
    const current = /CORE_SOURCE_HASH = "([0-9a-f]+)"/.exec(readFileSync(OUT, "utf8"))?.[1];
    if (current !== hash) { console.error(`core-wasm.js is stale: rebuild with node scripts/build-core-wasm.mjs`); process.exit(1); }
    console.log("core-wasm.js is current");
    process.exit(0);
  }
  const tmp = mkdtempSync(join(tmpdir(), "pf-core-"));
  try {
    const wasm = join(tmp, "core.wasm");
    const sources = readdirSync(NATIVE).filter((n) => n.endsWith(".cpp")).sort().map((n) => join(NATIVE, n));
    execFileSync("em++", [...FLAGS, ...sources, "-o", wasm], { stdio: "inherit" });
    const bytes = readFileSync(wasm);
    const version = execFileSync("em++", ["--version"], { encoding: "utf8" }).split("\n")[0];
    writeFileSync(OUT, [
      "// GENERATED by scripts/build-core-wasm.mjs from native/ — do not edit by hand.",
      `// ${version}`,
      `// ${bytes.length} bytes of WebAssembly. test/core-wasm.test.js checks the hash below`,
      "// against native/ so a C++ change without a rebuild fails.",
      `export const CORE_SOURCE_HASH = "${hash}";`,
      `export const CORE_WASM_BASE64 = "${bytes.toString("base64")}";`,
      "",
    ].join("\n"));
    console.log(`wrote ${OUT} (${bytes.length} bytes wasm)`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}
